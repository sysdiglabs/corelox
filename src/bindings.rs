//! Rust bindings for the generated header, and the C code behind them.

use std::ffi::OsStr;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::{Builder, Error};

/// Generates the C header, Rust bindings for its accessors, and the accessors
/// compiled to BPF bitcode, for use from build.rs:
///
/// ```no_run
/// let out_dir = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
/// let header = corelox_build::Builder::new().glob("src/**/*.rs");
/// corelox_build::Bindgen::new(header, out_dir.join("corelox"))
///     // only needed if libbpf's headers aren't in a default include path
///     .include_dir("vendor/libbpf/include")
///     .generate()
///     .unwrap();
/// ```
///
/// The accessors are `static inline` C functions, so bindgen also emits
/// non-inline wrappers for them in C (see `--wrap-static-fns`). These get
/// compiled with clang to LLVM bitcode. The linker (bpf-linker) links the
/// bitcode with the Rust code through LTO.
///
/// Also prints `cargo:rerun-if-changed` for all the Rust sources scanned
/// by `header`.
pub struct Bindgen {
    header: Builder,
    out_dir: PathBuf,
    include_dirs: Vec<PathBuf>,
    clang: Option<PathBuf>,
    type_check: TypeCheck,
}

/// The BTF that the build checks the types of `#[btf]` fields against.
///
/// At load time, the accessors also check the types. If the types do not
/// match the kernel that loads the program, the accessors reject it. The
/// build-time check finds mismatches earlier and shows source locations,
/// but it uses only one kernel.
///
/// Mismatches are errors. Missing structs and members are only warnings,
/// because other kernels can have them.
#[derive(Debug, Clone, Default)]
pub enum TypeCheck {
    /// The BTF of the running kernel (`/sys/kernel/btf/vmlinux`). If it is not
    /// available, the build skips the check.
    #[default]
    RunningKernel,
    /// A raw BTF file, for example `/sys/kernel/btf/vmlinux` from the target machine
    File(PathBuf),
    Off,
}

const RUNNING_KERNEL_BTF: &str = "/sys/kernel/btf/vmlinux";

/// Files generated by [`Bindgen`], all in the output directory.
#[derive(Debug, Clone)]
pub struct OutputPaths {
    /// The C header (`btf.h`)
    pub header: PathBuf,
    /// Rust bindings for the accessors (`bindings.rs`), to be `include!`d
    pub bindings: PathBuf,
    /// Non-inline C wrappers for the accessors (`wrappers.c`)
    pub wrappers: PathBuf,
    /// `wrappers.c` compiled to BPF LLVM bitcode (`wrappers.bc`)
    pub wrappers_bitcode: PathBuf,
}

impl OutputPaths {
    pub fn new(out_dir: impl AsRef<Path>) -> Self {
        let out_dir = out_dir.as_ref();
        Self {
            header: out_dir.join("btf.h"),
            bindings: out_dir.join("bindings.rs"),
            wrappers: out_dir.join("wrappers.c"),
            wrappers_bitcode: out_dir.join("wrappers.bc"),
        }
    }
}

/// A [`Bindgen`] with the header written and bindgen configured,
/// ready to [`generate`](Prepared::generate) the rest.
pub struct Prepared {
    pub paths: OutputPaths,
    /// bindgen, configured for the header. Can be customized before generating.
    pub bindgen: bindgen::Builder,
    clang: PathBuf,
    include_dirs: Vec<PathBuf>,
}

impl Bindgen {
    /// `out_dir` gets all the generated files. For example, use a subdirectory of `$OUT_DIR`.
    pub fn new(header: Builder, out_dir: impl AsRef<Path>) -> Self {
        Self {
            header,
            out_dir: out_dir.as_ref().to_owned(),
            include_dirs: Vec::new(),
            clang: None,
            type_check: TypeCheck::default(),
        }
    }

    /// Adds a directory to search for included headers, for example the
    /// libbpf headers `bpf/*.h`. Binding generation and wrapper compilation
    /// both use it.
    pub fn include_dir(mut self, dir: impl AsRef<Path>) -> Self {
        self.include_dirs.push(dir.as_ref().to_owned());
        self
    }

    /// Sets the clang binary used to compile the wrappers.
    /// Defaults to `$CLANG`, or `clang` from `$PATH`.
    pub fn clang(mut self, path: impl AsRef<Path>) -> Self {
        self.clang = Some(path.as_ref().to_owned());
        self
    }

    /// Sets what to check the field types against, see [`TypeCheck`].
    pub fn type_check(mut self, type_check: TypeCheck) -> Self {
        self.type_check = type_check;
        self
    }

    /// Writes the header and configures bindgen for it.
    pub fn prepare(self) -> Result<Prepared, Error> {
        fs::create_dir_all(&self.out_dir).map_err(|source| Error::Io {
            path: self.out_dir.clone(),
            source,
        })?;
        let paths = OutputPaths::new(&self.out_dir);

        let sources = self.header.read_sources()?;
        for (path, _) in &sources {
            println!("cargo:rerun-if-changed={}", path.display());
        }
        let btf = load_btf(&self.type_check)?;
        let (header, warnings) = crate::generate_checked_header(sources, btf.as_ref())?;
        for warning in warnings {
            println!("cargo:warning={warning}");
        }
        fs::write(&paths.header, header).map_err(|source| Error::Io {
            path: paths.header.clone(),
            source,
        })?;

        let bindgen = bindgen::Builder::default()
            .header(paths.header.to_string_lossy())
            .clang_arg("--target=bpf")
            .clang_args(include_args(&self.include_dirs))
            // only the accessors: the structs are already defined in Rust
            .allowlist_function("co_re_.*")
            .allowlist_type("co_re_.*")
            .wrap_static_fns(true)
            // bindgen adds the extension
            .wrap_static_fns_path(paths.wrappers.with_extension(""))
            .use_core()
            .ctypes_prefix("core::ffi")
            .layout_tests(false);

        println!("cargo:rerun-if-env-changed=CLANG");
        let clang = self
            .clang
            .or_else(|| std::env::var_os("CLANG").map(PathBuf::from))
            .unwrap_or_else(|| "clang".into());

        Ok(Prepared {
            paths,
            bindgen,
            clang,
            include_dirs: self.include_dirs,
        })
    }

    /// Generates everything, see [`Prepared::generate`].
    pub fn generate(self) -> Result<OutputPaths, Error> {
        self.prepare()?.generate()
    }
}

impl Prepared {
    /// Generates the bindings and wrappers, compiles the wrappers and tells
    /// cargo to link them into the program being built. The path to the
    /// bindings is passed to the program as `$CORELOX_BINDINGS`, which is
    /// where the `#[btf]` macro finds them.
    pub fn generate(self) -> Result<OutputPaths, Error> {
        // if there are no wrappers, bindgen does not write the file, so remove stale ones
        remove_if_exists(&self.paths.wrappers)?;

        let bindings = self.bindgen.generate().map_err(Error::Bindgen)?;
        bindings
            .write_to_file(&self.paths.bindings)
            .map_err(|source| Error::Io {
                path: self.paths.bindings.clone(),
                source,
            })?;

        if !self.paths.wrappers.exists() {
            fs::write(&self.paths.wrappers, "").map_err(|source| Error::Io {
                path: self.paths.wrappers.clone(),
                source,
            })?;
        }
        if let Some(rustc) = std::env::var_os("RUSTC") {
            check_llvm_versions(&rustc, &self.clang)?;
        }
        compile_wrappers(&self.clang, &self.include_dirs, &self.paths)?;
        println!(
            "cargo:rustc-link-arg={}",
            self.paths.wrappers_bitcode.display()
        );
        // for the code generated by the #[btf] macro to `include!`
        println!(
            "cargo:rustc-env=CORELOX_BINDINGS={}",
            self.paths.bindings.display()
        );
        Ok(self.paths)
    }
}

fn load_btf(type_check: &TypeCheck) -> Result<Option<btf_rs::Btf>, Error> {
    let path = match type_check {
        TypeCheck::Off => return Ok(None),
        TypeCheck::RunningKernel => {
            let path = Path::new(RUNNING_KERNEL_BTF);
            if !path.exists() {
                println!(
                    "cargo:warning=not checking #[btf] field types: {} doesn't exist",
                    path.display()
                );
                return Ok(None);
            }
            path
        }
        TypeCheck::File(path) => path.as_path(),
    };
    // for example, after a boot into another kernel
    println!("cargo:rerun-if-changed={}", path.display());
    btf_rs::Btf::from_file(path).map(Some).map_err(Error::Btf)
}

fn include_args(dirs: &[PathBuf]) -> impl Iterator<Item = String> + '_ {
    dirs.iter().map(|dir| format!("-I{}", dir.display()))
}

fn remove_if_exists(path: &Path) -> Result<(), Error> {
    match fs::remove_file(path) {
        Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(Error::Io {
            path: path.to_owned(),
            source: e,
        }),
        _ => Ok(()),
    }
}

/// Makes sure that bpf-linker can read the bitcode of the wrappers. With its
/// default `rust-llvm` feature, bpf-linker uses the LLVM of the Rust
/// toolchain that does the build. An older LLVM cannot read bitcode from a
/// newer one. Then the link fails with only `Invalid record`.
///
/// If one of the versions is unknown, the check does nothing.
fn check_llvm_versions(rustc: &OsStr, clang: &Path) -> Result<(), Error> {
    let (Some(rustc_version), Some(clang_version)) = (
        command_output(rustc.as_ref(), "-vV"),
        command_output(clang, "--version"),
    ) else {
        return Ok(());
    };
    compare_llvm_versions(&rustc_version, &clang_version)
}

fn command_output(program: &Path, arg: &str) -> Option<String> {
    let output = Command::new(program).arg(arg).output().ok()?;
    output
        .status
        .success()
        .then(|| String::from_utf8_lossy(&output.stdout).into_owned())
}

fn compare_llvm_versions(rustc_version: &str, clang_version: &str) -> Result<(), Error> {
    let (Some(rust), Some(clang)) = (
        llvm_major(rustc_version, "LLVM version: "),
        llvm_major(clang_version, "clang version "),
    ) else {
        return Ok(());
    };
    if clang > rust {
        return Err(Error::LlvmVersion { clang, rust });
    }
    Ok(())
}

/// Returns the major version following `prefix` in `output`.
fn llvm_major(output: &str, prefix: &str) -> Option<u32> {
    let (_, version) = output.split_once(prefix)?;
    let major = version.split(|c: char| !c.is_ascii_digit()).next()?;
    major.parse().ok()
}

fn compile_wrappers(
    clang: &Path,
    include_dirs: &[PathBuf],
    paths: &OutputPaths,
) -> Result<(), Error> {
    let mut cmd = Command::new(clang);
    // bitcode and not an object file, for LTO with the Rust code.
    // CO-RE relocations refer to BTF, which needs -g.
    cmd.args(["--target=bpf", "-O2", "-g", "-emit-llvm", "-c"])
        .args(include_args(include_dirs))
        .arg(&paths.wrappers)
        .arg("-o")
        .arg(&paths.wrappers_bitcode);

    let output = cmd.output().map_err(|source| Error::Io {
        path: clang.to_owned(),
        source,
    })?;
    if !output.status.success() {
        return Err(Error::Clang {
            command: format!("{cmd:?}"),
            status: output.status,
            stderr: String::from_utf8_lossy(&output.stderr).into_owned(),
        });
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const RUSTC_22: &str = "rustc 1.98.1 (48a229cea 2026-09-01)
binary: rustc
host: x86_64-unknown-linux-gnu
release: 1.98.1
LLVM version: 22.1.8
";

    #[test]
    fn llvm_versions() {
        let clang = |version| {
            format!("Ubuntu clang version {version} (1ubuntu1)\nTarget: x86_64-pc-linux-gnu\n")
        };
        assert!(compare_llvm_versions(RUSTC_22, &clang("18.1.3")).is_ok());
        assert!(compare_llvm_versions(RUSTC_22, &clang("22.1.0")).is_ok());
        assert!(matches!(
            compare_llvm_versions(RUSTC_22, &clang("23.0.0")),
            Err(Error::LlvmVersion {
                clang: 23,
                rust: 22
            })
        ));
        assert!(matches!(
            compare_llvm_versions(RUSTC_22, "clang version 23.1.0\n"),
            Err(Error::LlvmVersion {
                clang: 23,
                rust: 22
            })
        ));
    }

    #[test]
    fn unknown_llvm_versions_are_ok() {
        assert!(compare_llvm_versions("rustc 1.98.1\n", "clang version 99.0.0\n").is_ok());
        assert!(compare_llvm_versions(RUSTC_22, "gcc (GCC) 14.2.0\n").is_ok());
    }
}
