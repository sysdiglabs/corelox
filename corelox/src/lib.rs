//! The `#[btf]` attribute macro.

use corelox_parser::types::primitive_c_type;
use corelox_parser::{BtfItem, BtfItemField, BtfStruct};
use zyn::syn::ext::IdentExt;
use zyn::syn::{self, Ident, ItemStruct, Type, TypeArray};
use zyn::{Diagnostic, TokenStream, format_ident};

/// Turns a struct into a handle to a kernel struct, with CO-RE accessors
/// for its fields.
///
/// ```ignore
/// #[btf]
/// pub struct task_struct {
///     pub pid: i32,
///     pub real_parent: *const task_struct,
///     #[btf(path = "se.vruntime")]
///     pub vruntime: u64,
/// }
///
/// let task = task_struct::from_ptr(ptr);
/// let parent: task_struct = task.real_parent()?;
/// let pid: i32 = parent.pid()?;
/// if task_struct::has_vruntime() { ... }
/// ```
///
/// The struct becomes a `Copy` wrapper around a pointer to the kernel struct,
/// without any fields. Each field `foo` gets a `foo()` method, which reads it
/// with `bpf_probe_read_kernel`. On failure, the method returns the negative
/// error code. The field also gets a `has_foo()` function, which tells whether
/// the running kernel has it.
/// Pointers to other `#[btf]` structs are returned as their wrappers.
///
/// The methods call the C accessors generated by `corelox_build::Bindgen` from
/// build.rs, which has to scan the file with the struct.
#[proc_macro_attribute]
pub fn btf(
    attr: proc_macro::TokenStream,
    item: proc_macro::TokenStream,
) -> proc_macro::TokenStream {
    expand(attr.into(), item.into()).into()
}

fn expand(attr: TokenStream, item: TokenStream) -> TokenStream {
    try_expand(attr, item).unwrap_or_else(Diagnostic::emit)
}

fn try_expand(attr: TokenStream, item: TokenStream) -> zyn::Result<TokenStream> {
    let attr = BtfStruct::from_tokens(attr)?;
    let item: ItemStruct = syn::parse2(item).map_err(Diagnostic::from)?;
    let item = BtfItem::new(attr, &item)?;

    let mut accessors = Vec::new();
    let mut errors: Option<syn::Error> = None;
    for field in &item.fields {
        match Accessor::new(&item, field) {
            Ok(accessor) => accessors.push(accessor),
            Err(e) => match &mut errors {
                Some(errors) => errors.combine(e),
                None => errors = Some(e),
            },
        }
    }
    if let Some(errors) = errors {
        return Err(errors.into());
    }

    Ok(render(&item, &accessors))
}

struct Accessor<'a> {
    field: &'a BtfItemField,
    /// What the accessor returns, laid out like the C member
    ty: Type,
    /// The `has_*` function
    has: Ident,
    /// The bindgen functions for the C accessors
    c_read: Ident,
    c_has: Ident,
}

impl<'a> Accessor<'a> {
    fn new(item: &BtfItem, field: &'a BtfItemField) -> syn::Result<Self> {
        // the names used by the C header (see corelox-build's templates/header.h)
        let (s, f) = (item.ident.unraw(), field.ident.unraw());
        Ok(Self {
            field,
            ty: value_type(&field.ty)?,
            has: format_ident!("has_{f}"),
            c_read: format_ident!("co_re_{s}_{f}"),
            c_has: format_ident!("co_re_{s}_has_{f}"),
        })
    }
}

/// Maps a field type to the type the accessor returns. Pointers to other
/// `#[btf]` structs become the structs' wrappers, which have the same layout.
///
/// Non-primitive types can only be `#[btf]` structs. Header generation
/// rejects all other types.
fn value_type(ty: &Type) -> syn::Result<Type> {
    match ty {
        Type::Paren(p) => value_type(&p.elem),
        Type::Group(g) => value_type(&g.elem),
        Type::Ptr(p) => match &*p.elem {
            Type::Path(pointee) if primitive_c_type(&pointee.path).is_none() => {
                Ok(Type::Path(pointee.clone()))
            }
            _ => Ok(ty.clone()),
        },
        Type::Array(a) => Ok(Type::Array(TypeArray {
            elem: Box::new(value_type(&a.elem)?),
            ..a.clone()
        })),
        Type::Path(p) if primitive_c_type(&p.path).is_some() => Ok(ty.clone()),
        _ => Err(syn::Error::new_spanned(
            ty,
            "unsupported #[btf] field type: #[btf] structs can't be accessed by value \
             (yet), use #[btf(path = \"...\")] to access their fields",
        )),
    }
}

fn render(item: &BtfItem, accessors: &[Accessor]) -> TokenStream {
    let ident = &item.ident;
    let vis = &item.vis;
    // the wrapper's layout is the pointer's, not the kernel struct's
    let attrs = item.attrs.iter().filter(|a| !a.path().is_ident("repr"));

    zyn::zyn! {
        @for (attr in attrs) {
            {{ attr }}
        }
        #[derive(Clone, Copy)]
        #[repr(transparent)]
        // the name has to match the kernel's
        #[allow(non_camel_case_types)]
        {{ vis }} struct {{ ident }}(*const ());

        const _: () = {
            #[allow(non_camel_case_types, non_upper_case_globals, non_snake_case, dead_code)]
            mod ffi {
                include!(env!(
                    "CORELOX_BINDINGS",
                    "the bindings for #[btf] structs are missing, generate them with corelox_build::Bindgen from build.rs"
                ));
            }

            impl {{ ident }} {
                /// Wraps a pointer to the kernel struct.
                #[inline(always)]
                {{ vis }} fn from_ptr(ptr: *const core::ffi::c_void) -> Self {
                    Self(ptr.cast())
                }

                /// Returns the pointer to the kernel struct.
                #[inline(always)]
                {{ vis }} fn as_ptr(self) -> *const core::ffi::c_void {
                    self.0.cast()
                }

                @for (a in accessors) {
                    @for (attr in a.field.attrs.iter()) {
                        {{ attr }}
                    }
                    #[inline(always)]
                    {{ a.field.vis }} fn {{ a.field.ident }}(self) -> core::result::Result<{{ a.ty }}, core::ffi::c_long> {
                        let mut out = core::mem::MaybeUninit::<{{ a.ty }}>::uninit();
                        // SAFETY: the C accessor reads with bpf_probe_read_kernel, which
                        // handles invalid pointers, into `out`, which is laid out like the member
                        let ret = unsafe { ffi::{{ a.c_read }}(self.as_ptr(), out.as_mut_ptr().cast()) };
                        if ret == 0 {
                            // SAFETY: the read succeeded
                            core::result::Result::Ok(unsafe { out.assume_init() })
                        } else {
                            core::result::Result::Err(ret)
                        }
                    }

                    #[inline(always)]
                    {{ a.field.vis }} fn {{ a.has }}() -> bool {
                        // SAFETY: only checks for the member's existence
                        unsafe { ffi::{{ a.c_has }}() }
                    }
                }
            }
        };
    }
    .into()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn expand_str(attr: &str, item: &str) -> String {
        expand(attr.parse().unwrap(), item.parse().unwrap()).to_string()
    }

    fn ty(src: &str) -> String {
        let ty = value_type(&syn::parse_str(src).unwrap()).unwrap();
        zyn::quote::quote!(#ty).to_string()
    }

    #[test]
    fn value_types() {
        assert_eq!(ty("u32"), "u32");
        assert_eq!(ty("core::ffi::c_int"), "core :: ffi :: c_int");
        assert_eq!(ty("*const u8"), "* const u8");
        assert_eq!(ty("*const c_void"), "* const c_void");
        assert_eq!(ty("*const *const task"), "* const * const task");
        assert_eq!(ty("*const task"), "task");
        assert_eq!(ty("*mut crate::x::task"), "crate :: x :: task");
        assert_eq!(ty("[u8; 16]"), "[u8 ; 16]");
        assert_eq!(ty("[*const task; 2]"), "[task ; 2]");
        assert!(value_type(&syn::parse_str("task").unwrap()).is_err());
        assert!(value_type(&syn::parse_str("[task; 2]").unwrap()).is_err());
    }

    #[test]
    fn expansion() {
        let out = expand_str(
            "",
            r#"
            /// docs
            #[repr(C)]
            pub struct task {
                /// pid docs
                pub pid: i32,
                parent: *const task,
                #[btf(path = "se.vruntime")]
                pub(crate) r#vruntime: u64,
            }
            "#,
        );
        // the output must be valid Rust
        let file: syn::File = syn::parse_str(&out).unwrap();
        let pretty = zyn::quote::quote!(#file).to_string();

        for expected in [
            "# [doc = \" docs\"] # [derive (Clone , Copy)] # [repr (transparent)] # [allow (non_camel_case_types)] pub struct task (* const ()) ;",
            "include ! (env ! (\"CORELOX_BINDINGS\"",
            "pub fn from_ptr (ptr : * const core :: ffi :: c_void) -> Self",
            "# [doc = \" pid docs\"] # [inline (always)] pub fn pid (self) -> core :: result :: Result < i32 , core :: ffi :: c_long >",
            "ffi :: co_re_task_pid (self . as_ptr () , out . as_mut_ptr () . cast ())",
            "pub fn has_pid () -> bool { unsafe { ffi :: co_re_task_has_pid () } }",
            // private field, returning the wrapper
            "# [inline (always)] fn parent (self) -> core :: result :: Result < task , core :: ffi :: c_long >",
            // named after the Rust field, not the C path
            "pub (crate) fn r#vruntime (self)",
            "ffi :: co_re_task_vruntime (",
            "pub (crate) fn has_vruntime ()",
        ] {
            assert!(pretty.contains(expected), "{expected}\n\n{pretty}");
        }
        assert!(!pretty.contains("repr (C)"), "{pretty}");
        assert!(!pretty.contains("# [btf"), "{pretty}");
    }

    #[test]
    fn errors() {
        let out = expand_str("", "struct Foo<T> { x: T }");
        assert!(out.contains("compile_error"), "{out}");
        assert!(out.contains("cannot be generic"), "{out}");

        let out = expand_str("bogus", "struct Foo { x: u32 }");
        assert!(out.contains("unknown argument `bogus`"), "{out}");

        let out = expand_str("", "struct Foo { a: Inner, b: [Inner; 2] }");
        assert_eq!(
            out.matches("can't be accessed by value").count(),
            2,
            "{out}"
        );
    }
}
